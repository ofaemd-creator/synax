"""Lossless UTF-8 byte tokenizer with reserved conversation role tokens."""

from __future__ import annotations
from typing import Final, Literal, TypedDict


class Message(TypedDict):
    role: Literal["system", "user", "assistant"]
    content: str


ROLES: Final = {"system": 256, "user": 257, "assistant": 258}
END: Final = 259
BOS: Final = 260
VOCAB_SIZE: Final = 261


def encode(messages: list[Message], *, generation: bool = False) -> list[int]:
    """Encode role boundaries without interpreting user text as control tokens."""
    tokens = [BOS]
    for message in messages:
        tokens.extend(
            [ROLES[message["role"]], *message["content"].encode("utf-8"), END]
        )
    if generation:
        tokens.append(ROLES["assistant"])
    return tokens


def decode(tokens: list[int]) -> str:
    """Decode generated bytes; incomplete final UTF-8 sequences are omitted."""
    return bytes(t for t in tokens if 0 <= t < 256).decode("utf-8", errors="ignore")
