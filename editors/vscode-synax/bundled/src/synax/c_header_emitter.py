#!/usr/bin/env python3
"""
SYNAX C/C++ ABI Header & Standalone Source Emitter (`src/synax/c_header_emitter.py`)
===================================================================================
Generates zero-dependency, self-contained ANSI C / C++ header (.h) and source (.c)
artifacts for embedding SYNAX kernels directly into bedside medical monitors,
defibrillators, flight controllers, or legacy embedded C++ codebases.

SPDX-License-Identifier: Apache-2.0
===================================================================================
"""

from __future__ import annotations

import hashlib
import os
import re
from pathlib import Path
from typing import Optional, Tuple

from synax_ir import SynaxIR
from synaxc import SynaxCodeGenerator, _format_c_float


def emit_c_header_and_source(
    ir: SynaxIR,
    output_dir: Path,
    out_prefix: Optional[str] = None,
) -> Tuple[Path, Path]:
    """
    Emit a standalone `<prefix>.h` and `<prefix>.c` file pair for `ir`.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    base_name = out_prefix or ir.name
    name_clean = re.sub(r"[^A-Za-z0-9_]+", "_", ir.name).strip("_")
    name_upper = name_clean.upper()

    header_path = output_dir / f"{base_name}.h"
    source_path = output_dir / f"{base_name}.c"

    # Compute hash of the kernel IR representation
    ir_digest = hashlib.sha256(f"{ir.name}:{ir.expr.to_c_scalar()}".encode("utf-8")).hexdigest()

    # --- 1. HEADER (.h) ---
    header_content = f"""/*
 * =============================================================================
 * SYNAX Autonomous Fault-Healing Kernel C/C++ ABI Header
 * =============================================================================
 * Kernel Name   : {name_clean}
 * Clinical Intent : "{ir.intent_text}"
 * Safety Mode   : {ir.safety.nonfinite_mode} (heal={ir.safety.heal_value})
 * SHA-256 Digest : {ir_digest}
 * Generated by   : SYNAX Compiler (v0.6.1)
 *
 * Compliance    : Designed for IEC 62304 Class C (Medical Safety-Critical)
 * Dependencies  : Zero external libraries (Pure C11 / C++17 ABI compatible)
 * =============================================================================
 */

#ifndef SYNAX_KERNEL_{name_upper}_H
#define SYNAX_KERNEL_{name_upper}_H

#ifdef __cplusplus
extern "C" {{
#endif

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>

/**
 * Execution telemetric status returned by the kernel.
 */
typedef struct {{
    size_t total_samples;
    size_t healed_nonfinite_samples;
    size_t clamped_samples;
}} synax_{name_clean}_status_t;

/**
 * Execute the fault-healing kernel across input buffers.
 *
 * @param a       Pointer to input vector A (contiguous float32 array).
 * @param b       Pointer to input vector B (can be NULL if single-vector kernel).
 * @param out     Pointer to pre-allocated output vector buffer.
 * @param n       Number of float32 elements to process.
 * @param status  Optional pointer to receive runtime anomaly statistics.
 * @return        0 on successful execution, negative error code on invalid parameters.
 */
int synax_{name_clean}_run(
    const float* restrict a,
    const float* restrict b,
    float* restrict out,
    size_t n,
    synax_{name_clean}_status_t* status
);

/**
 * Returns the immutable cryptographic SHA-256 digest of this kernel.
 */
const char* synax_{name_clean}_sha256(void);

#ifdef __cplusplus
}}
#endif

#endif /* SYNAX_KERNEL_{name_upper}_H */
"""
    header_path.write_text(header_content, encoding="utf-8")

    # --- 2. SOURCE (.c) ---
    bound_hex = SynaxCodeGenerator._bound_u32_hex(ir.safety)
    c_expr = ir.expr.to_c_scalar(var_a="ai", var_b="bi", var_bias="0.25f")
    heal_lit = _format_c_float(ir.safety.heal_value)

    clamp_logic = ""
    if ir.safety.output_clamp is not None:
        lo = _format_c_float(ir.safety.output_clamp[0])
        hi = _format_c_float(ir.safety.output_clamp[1])
        clamp_logic = f"""
        if (res < {lo}) {{ res = {lo}; clamped++; }}
        else if (res > {hi}) {{ res = {hi}; clamped++; }}"""

    source_content = f"""/*
 * =============================================================================
 * SYNAX Standalone C11 Kernel Implementation: {name_clean}
 * =============================================================================
 * Autogenerated by SYNAX Compiler. Do not modify directly.
 * =============================================================================
 */

#include "{header_path.name}"
#include <math.h>
#include <string.h>

static const char* SYNAX_KERNEL_SHA256 = "{ir_digest}";

static inline bool synax_is_valid_f32(float x, uint32_t bound_u32) {{
    uint32_t bits;
    memcpy(&bits, &x, sizeof(bits));
    return (bits & 0x7FFFFFFFu) <= bound_u32;
}}

const char* synax_{name_clean}_sha256(void) {{
    return SYNAX_KERNEL_SHA256;
}}

int synax_{name_clean}_run(
    const float* restrict a,
    const float* restrict b,
    float* restrict out,
    size_t n,
    synax_{name_clean}_status_t* status
) {{
    if (!a || !out) return -1;
    if (n == 0) return 0;

    const uint32_t bound_u32 = {bound_hex};
    size_t healed = 0;
    size_t clamped = 0;

    for (size_t i = 0; i < n; ++i) {{
        float ai = a[i];
        float bi = b ? b[i] : 0.0f;

        if (!synax_is_valid_f32(ai, bound_u32)) {{
            ai = {heal_lit};
            healed++;
        }}
        if (b && !synax_is_valid_f32(bi, bound_u32)) {{
            bi = {heal_lit};
            healed++;
        }}

        float res = {c_expr};
{clamp_logic}

        out[i] = res;
    }}

    if (status) {{
        status->total_samples = n;
        status->healed_nonfinite_samples = healed;
        status->clamped_samples = clamped;
    }}

    return 0;
}}
"""
    source_path.write_text(source_content, encoding="utf-8")

    return header_path, source_path
