import os
import sys
import time
import hashlib
import subprocess
from typing import Optional
from synapse_neural_model import SynapseNanoModel, ASTNode

BASE_DIR = "/Users/o.farukaydin/.gemini/antigravity/scratch/synax"
BUILD_DIR = os.path.join(BASE_DIR, "build")

class SynaxNativeCompiler:
    def __init__(self):
        self.model = SynapseNanoModel()

    def synthesize_standalone_c(self, sx_text: str) -> tuple[str, ASTNode, str]:
        ast = self.model.parse_to_ast(sx_text)
        symbolic_str = self.model.natural_language_to_symbolic_expr(sx_text)
        c_scalar_expr = ast.to_c_scalar()
        human_formula = ast.to_human_formula()
        use_pure_neon = ast.can_use_pure_neon_intrinsics()
        neon_expr = ast.to_neon_f32x4() if use_pure_neon else ""

        if use_pure_neon:
            neon_block = f"""
            #define SYNAX_VEC_STEP(va, vb, vout) \\
                do {{ \\
                    float32x4_t res = {neon_expr}; \\
                    vout = vminq_f32(vmax_clamp, vmaxq_f32(vzero, res)); \\
                }} while(0)
            """
        else:
            # Trigonometrik/üstel ifadeler için 4x unrolled vektör boru hattı
            neon_block = f"""
            #define SYNAX_VEC_STEP(va, vb, vout) \\
                do {{ \\
                    float tmp_a[4], tmp_b[4], tmp_o[4]; \\
                    vst1q_f32(tmp_a, va); vst1q_f32(tmp_b, vb); \\
                    for (int k = 0; k < 4; ++k) {{ \\
                        const float* a = tmp_a; const float* b = tmp_b; int i = k; \\
                        float v = {c_scalar_expr}; \\
                        tmp_o[k] = isfinite(v) ? v : 0.0f; \\
                    }} \\
                    vout = vld1q_f32(tmp_o); \\
                }} while(0)
            """

        c_source = f"""
        // =====================================================================
        // AUTO-GENERATED BY SYNAXC v1.0 (TRUE NEURO-SYMBOLIC NATIVE COMPILER)
        // Formula AST : y[i] = {human_formula}
        // C Expression: y[i] = {c_scalar_expr}
        // =====================================================================
        #include <stdio.h>
        #include <stdlib.h>
        #include <stdint.h>
        #include <stddef.h>
        #include <math.h>
        #include <time.h>
        #if defined(__APPLE__)
        #include <dispatch/dispatch.h>
        #endif
        #if defined(__aarch64__) || defined(_M_ARM64)
        #include <arm_neon.h>
        #elif defined(__x86_64__) || defined(_M_X64)
        #include <immintrin.h>
        #endif

        static inline double now_us(void) {{
            struct timespec ts;
            clock_gettime(CLOCK_MONOTONIC, &ts);
            return (double)ts.tv_sec * 1e6 + (double)ts.tv_nsec / 1000.0;
        }}

        static inline float synax_immune_guard(float v) {{
            if (!isfinite(v)) return 0.0f;
            if (v < -1e6f) return -1e6f;
            if (v > 1e6f) return 1e6f;
            return v;
        }}

        size_t synax_immune_scan_and_heal(float* __restrict data, size_t n) {{
            size_t healed = 0;
            for (size_t i = 0; i < n; ++i) {{
                if (!isfinite(data[i]) || data[i] > 1e6f || data[i] < -1e6f) {{
                    data[i] = 0.0f;
                    healed++;
                }}
            }}
            return healed;
        }}

        // GEN-0: TinyMCU Scalar
        void gene_0_scalar(const float* __restrict a, const float* __restrict b, float* __restrict out, size_t n, float bias) {{
            #pragma clang loop vectorize(disable) unroll(disable)
            for (size_t i = 0; i < n; ++i) {{
                float v = {c_scalar_expr};
                out[i] = synax_immune_guard(v);
            }}
        }}

        // GEN-1: Superscalar Unrolled 4x
        void gene_1_unrolled(const float* __restrict a, const float* __restrict b, float* __restrict out, size_t n, float bias) {{
            #pragma clang loop vectorize(disable) unroll_count(4)
            for (size_t i = 0; i < n; ++i) {{
                float v = {c_scalar_expr};
                out[i] = synax_immune_guard(v);
            }}
        }}

        // GEN-2: Auto-Vectorized + L1D Cache Prefetch (Universal x86 AVX / ARM NEON)
        void gene_2_simd_prefetch(const float* __restrict a, const float* __restrict b, float* __restrict out, size_t n, float bias) {{
            for (size_t i = 0; i < n; ++i) {{
                if ((i & 63) == 0) {{
                    __builtin_prefetch(a + i + 64, 0, 3);
                    __builtin_prefetch(b + i + 64, 0, 3);
                }}
                float v = {c_scalar_expr};
                out[i] = v;
            }}
        }}

        // MUT-3: Asymmetric 4 P-Core Parallel + SIMD Prefetch
        void mut_3_parallel_4p(const float* __restrict a, const float* __restrict b, float* __restrict out, size_t n, float bias) {{
        #if defined(__APPLE__)
            const size_t chunks = 4;
            const size_t chunk_sz = (n / chunks) & ~15ULL;
            dispatch_apply(chunks, dispatch_get_global_queue(QOS_CLASS_USER_INTERACTIVE, 0), ^(size_t t) {{
                size_t start = t * chunk_sz;
                size_t end = (t == chunks - 1) ? n : (t + 1) * chunk_sz;
                gene_2_simd_prefetch(a + start, b + start, out + start, end - start, bias);
            }});
        #else
            gene_2_simd_prefetch(a, b, out, n, bias);
        #endif
        }}

        int main(int argc, char** argv) {{
            size_t N = 4000000;
            if (argc > 1) N = (size_t)atol(argv[1]);

            printf("╔══════════════════════════════════════════════════════════════════════════╗\\n");
            printf("║  ⚡ SYNAX NATIVE EXECUTABLE BINARY (Compiled by synaxc v1.0)            ║\\n");
            printf("╠══════════════════════════════════════════════════════════════════════════╣\\n");
            printf("║  • Semantik AST Formülü : y[i] = %-39s ║\\n", "{human_formula}");
            printf("║  • C99/SIMD İfadesi     : %-46.46s ║\\n", "{c_scalar_expr}");
            printf("╚══════════════════════════════════════════════════════════════════════════╝\\n");

            float* a = (float*)malloc(N * sizeof(float));
            float* b = (float*)malloc(N * sizeof(float));
            float* out = (float*)malloc(N * sizeof(float));
            for (size_t i = 0; i < N; ++i) {{
                a[i] = 1.5f + (float)(i % 10) * 0.1f;
                b[i] = 0.8f + (float)(i % 7) * 0.05f;
            }}

            // 3 bozuk sinyal enjekte et ve Immune Shield ile onar
            a[10] = NAN; a[1000] = INFINITY; a[50000] = -INFINITY;
            double t_h0 = now_us();
            size_t healed = synax_immune_scan_and_heal(a, N);
            double t_h1 = now_us();
            printf("  🛡️  [IMMUNE SHIELD] %zu bozuk sinyal %.2f ms icinde onarildi!\\n\\n", healed, (t_h1 - t_h0)/1000.0);

            typedef void (*gene_fn)(const float*, const float*, float*, size_t, float);
            const char* names[4] = {{
                "GEN-0 [TinyMCU-Scalar]",
                "GEN-1 [Unrolled-4x]",
                "GEN-2 [SIMD-L1D-Prefetch]",
                "MUT-3 [4P-Core-HyperSIMD]"
            }};
            gene_fn funcs[4] = {{ gene_0_scalar, gene_1_unrolled, gene_2_simd_prefetch, mut_3_parallel_4p }};
            double best_us[4] = {{ 1e18, 1e18, 1e18, 1e18 }};

            int winner = 0;
            for (int g = 0; g < 4; ++g) {{
                funcs[g](a, b, out, N, 0.25f); // Warmup
                for (int r = 0; r < 3; ++r) {{
                    double t0 = now_us();
                    funcs[g](a, b, out, N, 0.25f);
                    double dt = now_us() - t0;
                    if (dt < best_us[g]) best_us[g] = dt;
                }}
                if (best_us[g] < best_us[winner]) winner = g;
                printf("  🧬 %-26s -> En Iyi Sure: %8.1f µs\\n", names[g], best_us[g]);
            }}

            double speedup = best_us[0] / best_us[winner];
            printf("\\n  🏆 MİYELİNLENEN ŞAMPİYON DNA : %s (%.1f µs | %.2fx Hizlanma!)\\n", names[winner], best_us[winner], speedup);
            printf("  📊 Ornek Cikti (out[0..3])   : [%.4f, %.4f, %.4f, %.4f]\\n", out[0], out[1], out[2], out[3]);

            free(a); free(b); free(out);
            return 0;
        }}
        """
        return c_source, ast, symbolic_str

    def compile_to_binary(self, sx_text: str, output_bin_path: Optional[str] = None) -> str:
        os.makedirs(BUILD_DIR, exist_ok=True)
        h = hashlib.sha256(sx_text.encode("utf-8")).hexdigest()[:8]
        c_path = os.path.join(BUILD_DIR, f"synax_prog_{h}.c")
        bin_path = output_bin_path or os.path.join(BUILD_DIR, f"synax_prog_{h}_bin")

        c_source, ast, _ = self.synthesize_standalone_c(sx_text)
        with open(c_path, "w") as f:
            f.write(c_source)

        cmd = ["clang", "-O3", "-ffast-math", "-fno-finite-math-only", "-Wno-nan-infinity-disabled", c_path, "-lm", "-o", bin_path]
        subprocess.run(cmd, check=True)
        return bin_path


if __name__ == "__main__":
    compiler = SynaxNativeCompiler()
    if len(sys.argv) < 2:
        prompt = "niyet: a ile b'nin farkının karesinin karekökünü al, sapma ekle ve sigmoid uygula"
    else:
        arg = " ".join(sys.argv[1:])
        if os.path.exists(arg):
            with open(arg, "r") as f:
                prompt = f.read()
        else:
            prompt = arg

    bin_file = compiler.compile_to_binary(prompt)
    subprocess.run([bin_file])
